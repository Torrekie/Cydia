Result Runner::RunInternal(const std::vector<std::string> &arguments,
                           int statusFd,
                           const std::string *input,
                           const std::string *outputPath,
                           std::string *capturedOutput,
                           std::size_t maxCapturedBytes,
                           unsigned timeoutMilliseconds,
                           const std::function<bool()> &cancelled,
                           const NativeLaunchEnvironment *environment) const {
    // Retain owned immutable strings through spawn, including an explicit
    // empty environment. Invalid snapshots never reach descriptor setup.
    NativeLaunchEnvironment::Envp frozenEnvp;
    if (environment != NULL && !environment->BuildEnvp(&frozenEnvp)) return launchFailure(EINVAL);
    const bool bounded(timeoutMilliseconds != 0);
    const auto deadline(std::chrono::steady_clock::now() + std::chrono::milliseconds(timeoutMilliseconds));
    if (executable_.empty() || statusFd < -1 ||
        (bounded && (capturedOutput == NULL || outputPath != NULL)) ||
        (outputPath != NULL && outputPath->empty()) ||
        (outputPath != NULL && capturedOutput != NULL) ||
        (input != NULL && statusFd == STDIN_FILENO) ||
        ((outputPath != NULL || capturedOutput != NULL) && statusFd == STDOUT_FILENO))
        return launchFailure(EINVAL);
    if (bounded && cancelled && cancelled()) return launchFailure(ECANCELED);

    if (statusFd >= 0 && fcntl(statusFd, F_GETFD) == -1)
        return launchFailure(errno);

    int inputPipe[2] = {-1, -1};
    if (input != NULL && pipe(inputPipe) == -1)
        return launchFailure(errno);

    int outputPipe[2] = {-1, -1};
    if (capturedOutput != NULL && pipe(outputPipe) == -1) {
        const int error(errno);
        if (input != NULL) {
            (void) close(inputPipe[0]);
            (void) close(inputPipe[1]);
        }
        return launchFailure(error);
    }
#ifdef F_SETNOSIGPIPE
    if (input != NULL && fcntl(inputPipe[1], F_SETNOSIGPIPE, 1) == -1) {
        const int error(errno);
        (void) close(inputPipe[0]);
        (void) close(inputPipe[1]);
        return launchFailure(error);
    }
#endif

    std::vector<std::string> storage;
    storage.reserve(arguments.size() + 3);
    storage.push_back(executable_);
    storage.insert(storage.end(), arguments.begin(), arguments.end());

    if (statusFd >= 0 && !hasStatusArgument(arguments)) {
        storage.push_back("--status-fd");
        storage.push_back(std::to_string(statusFd));
    }

    std::vector<char *> argv;
    argv.reserve(storage.size() + 1);
    for (std::vector<std::string>::iterator it = storage.begin(); it != storage.end(); ++it)
        argv.push_back(const_cast<char *>(it->c_str()));
    argv.push_back(NULL);

    /* posix_spawn avoids forking a multithreaded UIKit process.  The Darwin
     * inherit action also clears close-on-exec on a caller-supplied status
     * descriptor, making the status-fd contract independent of how the pipe
     * was created (unlike dup2(fd, fd), which is a no-op on some systems).
     */
    posix_spawn_file_actions_t actions;
    int inheritedStatusFd = -1;
    int actionError = posix_spawn_file_actions_init(&actions);
    if (actionError != 0) {
        if (input != NULL) {
            (void) close(inputPipe[0]);
            (void) close(inputPipe[1]);
        }
        if (capturedOutput != NULL) {
            (void) close(outputPipe[0]);
            (void) close(outputPipe[1]);
        }
        return launchFailure(actionError);
    }

    if (statusFd >= 0) {
#ifdef __APPLE__
        actionError = posix_spawn_file_actions_addinherit_np(&actions, statusFd);
#else
        /* POSIX has no addinherit action. Duplicating through another child
         * descriptor makes dup2 clear FD_CLOEXEC on the requested number. */
        inheritedStatusFd = dup(statusFd);
        if (inheritedStatusFd == -1)
            actionError = errno;
        else {
            actionError = posix_spawn_file_actions_adddup2(&actions, inheritedStatusFd, statusFd);
            if (actionError == 0)
                actionError = posix_spawn_file_actions_addclose(&actions, inheritedStatusFd);
        }
#endif
        if (actionError != 0) {
            (void) posix_spawn_file_actions_destroy(&actions);
            if (inheritedStatusFd >= 0)
                (void) close(inheritedStatusFd);
            if (input != NULL) {
                (void) close(inputPipe[0]);
                (void) close(inputPipe[1]);
            }
            if (capturedOutput != NULL) {
                (void) close(outputPipe[0]);
                (void) close(outputPipe[1]);
            }
            return launchFailure(actionError);
        }
    }

    if (input != NULL) {
        actionError = posix_spawn_file_actions_adddup2(&actions, inputPipe[0], STDIN_FILENO);
        if (actionError == 0 && inputPipe[0] != STDIN_FILENO)
            actionError = posix_spawn_file_actions_addclose(&actions, inputPipe[0]);
        /* The child must not retain the parent's writer.  Otherwise a helper
         * that reads stdin to EOF waits forever because its own copy keeps
         * the pipe open after the parent finishes writing. */
        if (actionError == 0 && inputPipe[1] != STDIN_FILENO)
            actionError = posix_spawn_file_actions_addclose(&actions, inputPipe[1]);
        if (actionError != 0) {
            (void) posix_spawn_file_actions_destroy(&actions);
            if (inheritedStatusFd >= 0)
                (void) close(inheritedStatusFd);
            (void) close(inputPipe[0]);
            (void) close(inputPipe[1]);
            if (capturedOutput != NULL) {
                (void) close(outputPipe[0]);
                (void) close(outputPipe[1]);
            }
            return launchFailure(actionError);
        }
    }

    if (outputPath != NULL) {
        actionError = posix_spawn_file_actions_addopen(&actions, STDOUT_FILENO,
                                                       outputPath->c_str(),
                                                       O_WRONLY | O_CREAT | O_TRUNC,
                                                       0644);
        if (actionError != 0) {
            (void) posix_spawn_file_actions_destroy(&actions);
            if (inheritedStatusFd >= 0)
                (void) close(inheritedStatusFd);
            if (input != NULL) {
                (void) close(inputPipe[0]);
                (void) close(inputPipe[1]);
            }
            if (capturedOutput != NULL) {
                (void) close(outputPipe[0]);
                (void) close(outputPipe[1]);
            }
            return launchFailure(actionError);
        }
    }

    if (capturedOutput != NULL) {
        actionError = posix_spawn_file_actions_adddup2(&actions, outputPipe[1], STDOUT_FILENO);
        if (actionError == 0 && outputPipe[1] != STDOUT_FILENO)
            actionError = posix_spawn_file_actions_addclose(&actions, outputPipe[1]);
        if (actionError == 0 && outputPipe[0] != STDOUT_FILENO)
            actionError = posix_spawn_file_actions_addclose(&actions, outputPipe[0]);
        if (actionError != 0) {
            (void) posix_spawn_file_actions_destroy(&actions);
            if (inheritedStatusFd >= 0)
                (void) close(inheritedStatusFd);
            if (input != NULL) {
                (void) close(inputPipe[0]);
                (void) close(inputPipe[1]);
            }
            (void) close(outputPipe[0]);
            (void) close(outputPipe[1]);
            return launchFailure(actionError);
        }
    }

    posix_spawnattr_t attributes;
    bool attributesReady(false);
    int spawnError(0);
    if (bounded) {
        spawnError = posix_spawnattr_init(&attributes);
        attributesReady = spawnError == 0;
        if (spawnError == 0) spawnError = posix_spawnattr_setpgroup(&attributes, 0);
        if (spawnError == 0) spawnError = posix_spawnattr_setflags(&attributes, POSIX_SPAWN_SETPGROUP);
    }
    pid_t child;
    if (spawnError == 0) spawnError = posix_spawn(&child, executable_.c_str(), &actions,
        bounded ? &attributes : NULL, argv.data(), environment != NULL ? frozenEnvp.data() : environ);
    if (attributesReady) (void) posix_spawnattr_destroy(&attributes);
    (void) posix_spawn_file_actions_destroy(&actions);
    if (inheritedStatusFd >= 0)
        (void) close(inheritedStatusFd);
    if (spawnError != 0) {
        if (input != NULL) {
            (void) close(inputPipe[0]);
            (void) close(inputPipe[1]);
        }
        if (capturedOutput != NULL) {
            (void) close(outputPipe[0]);
            (void) close(outputPipe[1]);
        }
        return launchFailure(spawnError);
    }

    if (bounded) {
        close(outputPipe[1]);
        int failure(0), status(0);
        const int flags(fcntl(outputPipe[0], F_GETFL));
        if (flags < 0 || fcntl(outputPipe[0], F_SETFL, flags | O_NONBLOCK) != 0) failure = errno;
        std::size_t inputOffset(0);
        if (input != NULL) {
            close(inputPipe[0]); inputPipe[0] = -1;
            const int inputFlags(fcntl(inputPipe[1], F_GETFL));
            if (inputFlags < 0 || fcntl(inputPipe[1], F_SETFL, inputFlags | O_NONBLOCK) != 0) failure = errno;
            if (input->empty()) { close(inputPipe[1]); inputPipe[1] = -1; }
        }
        bool eof(false), reaped(false);
        char buffer[4096];
        while (failure == 0 && !reaped) {
            if (cancelled && cancelled()) { failure = ECANCELED; break; }
            if (std::chrono::steady_clock::now() >= deadline) { failure = ETIMEDOUT; break; }
            if (inputPipe[1] >= 0) {
                const ssize_t written(boundedWrite(inputPipe[1], input->data() + inputOffset,
                    std::min<std::size_t>(4096, input->size() - inputOffset)));
                if (written > 0) {
                    inputOffset += static_cast<std::size_t>(written);
                    if (inputOffset == input->size()) { close(inputPipe[1]); inputPipe[1] = -1; }
                } else if (written == 0 || (errno != EINTR && errno != EAGAIN && errno != EWOULDBLOCK)) {
                    failure = written == 0 ? EIO : errno; break;
                }
            }
            if (!eof) {
                const ssize_t count(read(outputPipe[0], buffer, sizeof(buffer)));
                if (count > 0) {
                    const std::size_t amount(static_cast<std::size_t>(count));
                    if (amount > maxCapturedBytes || capturedOutput->size() > maxCapturedBytes - amount) { failure = EFBIG; break; }
                    capturedOutput->append(buffer, amount); continue;
                }
                if (count == 0) { eof = true; close(outputPipe[0]); outputPipe[0] = -1; }
                else if (errno != EINTR && errno != EAGAIN && errno != EWOULDBLOCK) { failure = errno; break; }
            }
            // Do not reap while descendants still retain stdout: reserving
            // the direct child's PID prevents process-group identity reuse.
            if (eof && inputPipe[1] < 0) {
                const pid_t waited(waitpid(child, &status, WNOHANG));
                if (waited == child) { reaped = true; break; }
                if (waited < 0 && errno != EINTR) { failure = errno; break; }
            }
            struct pollfd descriptors[2]; nfds_t count(0);
            if (!eof) descriptors[count++] = {outputPipe[0], POLLIN, 0};
            if (inputPipe[1] >= 0) descriptors[count++] = {inputPipe[1], POLLOUT, 0};
            const int polled(poll(descriptors, count, 25));
            if (polled < 0 && errno != EINTR) { failure = errno; break; }
        }
        if (outputPipe[0] >= 0) close(outputPipe[0]);
        if (inputPipe[1] >= 0) {
            close(inputPipe[1]);
            if (failure == 0 && inputOffset != input->size()) failure = EPIPE;
        }
        if (!reaped) {
            // Bounded helpers own no package transaction; terminate the
            // private group so children cannot retain pipes or staging files.
            (void) kill(-child, SIGKILL);
            (void) kill(child, SIGKILL);
            pid_t waited;
            do { waited = waitpid(child, &status, 0); } while (waited < 0 && errno == EINTR);
            if (waited < 0 && failure == 0) failure = errno;
        }
        return failure != 0 ? launchFailure(failure) : fromWaitStatus(status);
    }

    int inputError = 0;
    if (input != NULL) {
        (void) close(inputPipe[0]);
        size_t offset = 0;
        while (offset != input->size()) {
            ssize_t written = write(inputPipe[1], input->data() + offset, input->size() - offset);
            if (written > 0) {
                offset += static_cast<size_t>(written);
                continue;
            }
            if (written == -1 && errno == EINTR)
                continue;
            inputError = written == -1 ? errno : EIO;
            break;
        }
        (void) close(inputPipe[1]);
    }

    int outputError = 0;
    if (capturedOutput != NULL) {
        (void) close(outputPipe[1]);
        char buffer[4096];
        for (;;) {
            const ssize_t count(read(outputPipe[0], buffer, sizeof(buffer)));
            if (count > 0) {
                const std::size_t available(maxCapturedBytes > capturedOutput->size() ?
                    maxCapturedBytes - capturedOutput->size() : 0);
                const std::size_t copy(std::min<std::size_t>(available, static_cast<std::size_t>(count)));
                capturedOutput->append(buffer, copy);
                if (copy != static_cast<std::size_t>(count) && outputError == 0)
                    outputError = EFBIG;
                continue;
            }
            if (count == -1 && errno == EINTR)
                continue;
            if (count == -1)
                outputError = errno;
            break;
        }
        (void) close(outputPipe[0]);
    }

    int status;
    pid_t waited;
    do {
        waited = waitpid(child, &status, 0);
    } while (waited == -1 && errno == EINTR);

    if (waited == -1)
        return launchFailure(errno);

    if (inputError != 0)
        return launchFailure(inputError);
    if (outputError != 0)
        return launchFailure(outputError);
    return fromWaitStatus(status);
}

